function antigravityAgent(
  ctx: ClientContext,
  name: string,
  description: string,
  body: string,
  opts: { main: boolean; withMcp: boolean; model?: string },
): ProjectionFile {
  const lines = [
    '---',
    `name: ${name}`,
    `description: ${yamlString(description)}`,
    `mainAgent: ${opts.main}`,
    `subagent: ${!opts.main}`,
  ];
  if (opts.model) lines.push(`model: ${opts.model}`);
  if (opts.withMcp) {
    lines.push(
      'mcpServers:',
      `  - name: ${SQUAD_STATE_KEY}`,
      `    command: ${yamlString(ctx.mcp.command)}`,
      `    args: [${ctx.mcp.args.map(yamlString).join(', ')}]`,
    );
  }
  lines.push('---', GENERATED_NOTE, '', body);
  return { kind: 'managed', path: `.agents/agents/${name}.md`, content: lines.join('\n') + '\n' };
}

