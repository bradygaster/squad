function modelFor(ctx: ClientContext, client: ClientId, slug: string): string | undefined {
  const m = ctx.memberModels?.[client];
  const v = m?.[slug] ?? m?.['*'];
  // Model ids are written unquoted into YAML/TOML: accept only plain id characters.
  return v && /^[A-Za-z0-9._:/@\[\]+-]+$/.test(v) ? v : undefined;
}

function claudeMember(m: TeamMember, ctx: ClientContext): ProjectionFile {
  const slug = slugifyMember(m.name);
  const squadDir = ctx.squadDir ?? '.squad';
  const model = modelFor(ctx, 'claude', slug);
  return {
    kind: 'managed',
    path: `.claude/agents/squad-${slug}.md`,
    content:
      frontmatter([
        ['name', `squad-${slug}`],
        ['description', yamlString(`Squad specialist ${m.name} (${m.role}). Use for work routed to ${m.name}.`)],
        ['tools', 'Read, Write, Edit, Bash, Glob, Grep, mcp__squad_state'],
        ...(model ? ([['model', model]] as Array<[string, string]>) : []),
      ]) +
      `${GENERATED_NOTE}\n\nYou are ${m.name}, the ${m.role} on this Squad team.\nFirst read your charter at \`${squadDir}/agents/${slug}/charter.md\` and follow it. Record decisions with the \`squad_decide\` MCP tool and append learnings to your history with \`squad_state_append\`.\n`,
  };
}

