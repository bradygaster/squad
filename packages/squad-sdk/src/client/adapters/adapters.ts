/**
 * Parse a `--client` value: comma-separated ids or `all`. Returns unique ids in
 * canonical order. Throws on unknown ids.
 */
export function parseClients(value: string | readonly string[] | undefined): ClientId[] {
  if (value === undefined) return [];
  const parts = (typeof value === 'string' ? value.split(',') : [...value])
    .map((p) => p.trim().toLowerCase())
    .filter(Boolean);
  if (parts.length === 0) throw new Error(`No client specified. Valid clients: ${CLIENT_IDS.join(', ')}, all`);
  const wanted = new Set<ClientId>();
  for (const p of parts) {
    if (p === 'all') {
      CLIENT_IDS.forEach((c) => wanted.add(c));
    } else if ((CLIENT_IDS as readonly string[]).includes(p)) {
      wanted.add(p as ClientId);
    } else {
      throw new Error(`Unknown client "${p}". Valid clients: ${CLIENT_IDS.join(', ')}, all`);
    }
  }
  return CLIENT_IDS.filter((c) => wanted.has(c));
}
