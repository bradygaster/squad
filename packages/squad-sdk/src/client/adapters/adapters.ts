const tomlString = (s: string) => JSON.stringify(s);
const tomlArray = (a: string[]) => `[${a.map(tomlString).join(', ')}]`;

/**
 * TOML multi-line basic string. Backslash is the escape character and a run of
 * three quotes would close the literal, so both are escaped; the newline right
 * after the opening delimiter is trimmed by TOML.
 */
export function tomlMultilineString(s: string): string {
  const body = s
    .replace(/\\/g, '\\\\')
    .replace(/"""/g, '""\\"')
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
  return `"""\n${body}"""`;
}

