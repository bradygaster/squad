export const SQUAD_STATE_KEY = 'squad_state';
const DESCRIPTION =
  'Squad coordinator: routes work to a team of specialist agents and keeps shared team state consistent via the squad_state MCP backend.';
const GENERATED_NOTE_TEXT = 'Generated by Squad. Managed file: refreshed by `squad upgrade`; edit .squad/ instead.';
const GENERATED_NOTE = `<!-- ${GENERATED_NOTE_TEXT} -->`;

type Json = Record<string, unknown>;

function isObject(v: unknown): v is Json {
  return !!v && typeof v === 'object' && !Array.isArray(v);
}

/**
 * Insert/refresh `<container>.squad_state`. Squad owns the launch fields
 * (`launch`); anything else already on the entry (env, tool filters, custom
 * fields) and every other server/top-level key is preserved. `defaults` only
 * apply when the entry did not previously exist or lacks the key.
 */
export function mergeMcpServer(
  existing: Json,
  container: string,
  launch: Json,
  defaults: Json = {},
  topLevelDefaults: Json = {},
): Json {
  const out: Json = { ...existing };
  for (const [k, v] of Object.entries(topLevelDefaults)) if (!(k in out)) out[k] = v;
  if (out[container] !== undefined && !isObject(out[container])) {
    throw new Error(`Refusing to overwrite "${container}": expected a JSON object`);
  }
  const servers: Json = isObject(out[container]) ? { ...(out[container] as Json) } : {};
  if (servers[SQUAD_STATE_KEY] !== undefined && !isObject(servers[SQUAD_STATE_KEY])) {
    throw new Error(`Refusing to overwrite "${container}.${SQUAD_STATE_KEY}": expected a JSON object`);
  }
  const prev = isObject(servers[SQUAD_STATE_KEY]) ? (servers[SQUAD_STATE_KEY] as Json) : {};
  const entry: Json = { ...prev };
  for (const [k, v] of Object.entries(defaults)) if (!(k in entry)) entry[k] = v;
  Object.assign(entry, launch);
  servers[SQUAD_STATE_KEY] = entry;
  out[container] = servers;
  return out;
}

function frontmatter(fields: Array<[string, string]>): string {
  return `---\n${fields.map(([k, v]) => `${k}: ${v}`).join('\n')}\n---\n`;
}

function yamlString(s: string): string {
  return JSON.stringify(s);
}

function mcpJson(ctx: ClientContext, withTools: boolean): ProjectionFile {
  return {
    kind: 'json',
    path: '.mcp.json',
    update: (existing) =>
      mergeMcpServer(
        existing,
        'mcpServers',
        { command: ctx.mcp.command, args: [...ctx.mcp.args] },
        withTools ? { env: {}, tools: ['*'] } : { env: {} },
      ),
  };
}

