/** `opencode.jsonc` is honored when it is the only OpenCode config present. */
export function opencodeConfigPath(root: string): 'opencode.json' | 'opencode.jsonc' {
  return !fs.existsSync(path.join(root, 'opencode.json')) && fs.existsSync(path.join(root, 'opencode.jsonc'))
    ? 'opencode.jsonc'
    : 'opencode.json';
}

