const ANTIGRAVITY_TOOLS = ['view_file', 'write_to_file', 'replace_file_content', 'grep_search', 'list_dir', 'run_command', 'invoke_subagent'];

function antigravityAgent(
  ctx: ClientContext,
  name: string,
  description: string,
  body: string,
  opts: { main: boolean; withMcp: boolean },
): ProjectionFile {
  const lines = [
    '---',
    `name: ${name}`,
    `description: ${yamlString(description)}`,
    `mainAgent: ${opts.main}`,
    `subagent: ${!opts.main}`,
  ];
  // Antigravity treats an omitted `tools` list as "none": without run_command the agent cannot use gh/git/npm.
  lines.push(`tools: [${ANTIGRAVITY_TOOLS.join(', ')}]`);
  if (opts.withMcp) {
    lines.push(
      'mcpServers:',
      `  - name: ${SQUAD_STATE_KEY}`,
      `    command: ${yamlString(ctx.mcp.command)}`,
      `    args: [${ctx.mcp.args.map(yamlString).join(', ')}]`,
    );
  }
  lines.push('---', GENERATED_NOTE, '', body);
  return { kind: 'managed', path: `.agents/agents/${name}.md`, content: lines.join('\n') + '\n' };
}

